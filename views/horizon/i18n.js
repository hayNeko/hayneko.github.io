	var locale = 'en';

	function normalize(loc) {
		if (!loc) return 'en';
		if (loc === 'zh' || loc === 'zh-cn' || loc === 'zh-hans') return 'zh-CN';
		if (loc === 'zh-tw' || loc === 'zh-hant' || loc === 'zh-hk') return 'zh-TW';
		if (loc === 'ja' || loc === 'ja-jp') return 'ja';
		if (loc === 'ko' || loc === 'ko-kr') return 'ko';
		if (loc === 'en' || loc === 'en-us' || loc === 'en-gb') return 'en';
		for (var i = 0; i < LOCALES.length; i++) if (LOCALES[i].toLowerCase() === String(loc).toLowerCase()) return LOCALES[i];
		return 'en';
	}

	function t(key, vars) {
		var table = MESSAGES[locale] || {};
		var text = table[key] != null ? table[key] : EN[key];
		if (text == null) return key;
		if (vars) {
			text = text.replace(/\{(\w+)\}/g, function (m, name) {
				return vars[name] != null ? vars[name] : m;
			});
		}
		return text;
	}

	function apply(root) {
		var scope = root && root.querySelectorAll ? root : global.document;
		if (scope === global.document) {
			scope.querySelectorAll('[data-hz-i18n]').forEach(translateNode);
		} else {
			if (scope.matches && scope.matches('[data-hz-i18n]')) translateNode(scope);
			scope.querySelectorAll('[data-hz-i18n]').forEach(translateNode);
		}
	}
	function translateNode(el) {
		var key = el.getAttribute('data-hz-i18n');
		if (key) el.textContent = t(key);
	}

	function detect() {
		try {
			if (global.i18n && typeof global.i18n.getLocale === 'function') return normalize(global.i18n.getLocale());
			var stored = global.localStorage.getItem('hayneko.i18n.locale');
			if (stored) return normalize(stored);
		} catch (e) { /* ignore */ }
		var nav = global.navigator && (global.navigator.language || global.navigator.userLanguage);
		return normalize(nav);
	}

	var HZI18n = {
		LOCALES: LOCALES,
		t: t,
		apply: apply,
		detect: detect,
		normalize: normalize,
		getLocale: function () { return locale; },
		setLocale: function (loc, opts) {
			locale = normalize(loc);
			try {
				global.localStorage.setItem('hayneko.horizon.lang', locale);
			} catch (e) { /* ignore */ }
			if (global.document && global.document.documentElement) global.document.documentElement.setAttribute('data-hz-lang', locale);
			var root = opts && opts.root;
			apply(root);
			try {
				global.dispatchEvent(new CustomEvent('hz:lang', { detail: { locale: locale } }));
			} catch (e) { /* CustomEvent missing */ }
			return locale;
		},
		init: function (preferred) {
			var loc = preferred || null;
			if (!loc) {
				try { loc = global.localStorage.getItem('hayneko.horizon.lang'); } catch (e) { /* ignore */ }
			}
			if (!loc) loc = detect();
			locale = normalize(loc);
			if (global.document && global.document.documentElement) global.document.documentElement.setAttribute('data-hz-lang', locale);
			return locale;
		}
	};

	global.HZI18n = HZI18n;
